# =============================================================================
# PRODUCT FORMATTING - Форматирование информации о товарах
# =============================================================================

def format_product_for_prompt(product: dict) -> str:
    """Format a single product for the prompt context."""
    name = product.get("name", "Неизвестный товар")
    category = product.get("category", "")
    form = product.get("product_form", "")
    price = product.get("price")
    is_available = product.get("is_available", False)
    origin = product.get("origin_country", "")
    
    # Build product line with explicit category and availability
    parts = [f"• {name}"]
    
    if category:
        parts.append(f"[Категория: {category}]")
    
    if form:
        parts.append(f"({form.lower()})")
    
    if is_available and price:
        parts.append(f"— {price:.0f} ₽/кг ✅ В НАЛИЧИИ")
    else:
        parts.append("— ❌ НЕТ В НАЛИЧИИ (ожидается поступление)")
    
    if origin:
        parts.append(f"Страна: {origin}")
    
    return " ".join(parts)


def format_products_context(products: list[dict]) -> str:
    """Format list of products for the prompt context, prioritizing available ones."""
    if not products:
        return "⚠️ По данному запросу товары НЕ НАЙДЕНЫ в базе. НЕ выдумывай товары и цены! Скажи клиенту, что не нашёл товар и предложи связаться с менеджером."
    
    # Separate available and unavailable products
    available = []
    unavailable = []
    
    for product in products:
        if product.get("is_available", False):
            available.append(product)
        else:
            unavailable.append(product)
    
    lines = []
    
    if available:
        lines.append("### ТОВАРЫ В НАЛИЧИИ (показывай эти в первую очередь!):")
        for product in available:
            lines.append(format_product_for_prompt(product))
    
    if unavailable:
        lines.append("\n### Товары НЕ в наличии (упоминай только если спросят или нет альтернатив):")
        for product in unavailable:
            lines.append(format_product_for_prompt(product))
    
    # Добавляем напоминание в конец контекста
    lines.append("\n⚠️ НАПОМИНАНИЕ: Выше — ВСЕ доступные товары. Если нужного товара нет в этом списке — его НЕТ в базе. Не выдумывай!")
    
    return "\n".join(lines)


# =============================================================================
# CONVERSATION HISTORY FORMATTING
# =============================================================================

def format_conversation_history(messages: list, max_messages: int = 10) -> str:
    """Format conversation history for the prompt."""
    from langchain_core.messages import HumanMessage, AIMessage
    
    if not messages:
        return "Это начало диалога."
    
    # Take last N messages
    recent_messages = messages[-max_messages:]
    
    lines = []
    for msg in recent_messages:
        if isinstance(msg, HumanMessage):
            lines.append(f"Клиент: {msg.content}")
        elif isinstance(msg, AIMessage):
            lines.append(f"Себастьян: {msg.content}")
    
    return "\n".join(lines) if lines else "Это начало диалога."


